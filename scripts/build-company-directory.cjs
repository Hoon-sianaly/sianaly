// Builds companies.html: every company page as a plain link, grouped by market and industry.
// The home list is drawn by JavaScript, so without this page crawlers find company pages mainly through
// the sitemap. Preferred shares are left out (their pages point search engines to the common stock).
//   node scripts/build-company-directory.cjs          write companies.html
//   node scripts/build-company-directory.cjs --check  fail if companies.html is out of date
const fs=require('node:fs'),path=require('node:path'),vm=require('node:vm');
const root=path.resolve(__dirname,'..'),output=path.join(root,'companies.html');
const esc=value=>String(value).replace(/[&<>"']/g,ch=>({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&#39;'}[ch]));

function buildDirectory(){
 const catalog=JSON.parse(fs.readFileSync(path.join(root,'data/company-index.json'),'utf8'));
 const context=vm.createContext({});
 vm.runInContext(fs.readFileSync(path.join(root,'company-industries.js'),'utf8')+';this.industries=COMPANY_INDUSTRIES;',context);
 const industries=context.industries;
 const markets=[['KOSPI','코스피'],['KOSDAQ','코스닥']];
 const sections=markets.map(([market,label])=>{
  const companies=catalog.companies.filter(c=>c.market===market&&!c.key.includes('pref'));
  const groups=new Map();
  for(const c of companies){const group=industries[c.key]||'기타';if(!groups.has(group))groups.set(group,[]);groups.get(group).push(c);}
  const ordered=[...groups].sort((a,b)=>b[1].length-a[1].length||a[0].localeCompare(b[0],'ko'));
  const nav=ordered.map(([group,list],i)=>`<a href="#${market.toLowerCase()}-${i}">${esc(group)} <span>${list.length}</span></a>`).join('');
  const body=ordered.map(([group,list],i)=>`<section class="dir-group" id="${market.toLowerCase()}-${i}"><h3>${esc(group)} <span>${list.length}개</span></h3><ul>${list.map(c=>`<li><a href="/company?company=${encodeURIComponent(c.key)}">${esc(c.name)}</a><small>${esc(c.ticker)}</small></li>`).join('')}</ul></section>`).join('\n');
  return {market,label,count:companies.length,nav,body};
 });
 const total=sections.reduce((n,s)=>n+s.count,0);
 return `<!doctype html>
<html lang="ko"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><title>전체 기업 목록 · SIANALY</title>
<meta name="description" content="SIANALY에서 볼 수 있는 코스피·코스닥 상장 기업 ${total.toLocaleString('ko-KR')}곳을 시장과 업종별로 모았습니다. 기업 이름을 누르면 사업과 연간·분기 실적을 볼 수 있습니다.">
<meta property="og:type" content="website"><meta property="og:site_name" content="SIANALY"><meta property="og:locale" content="ko_KR"><meta property="og:title" content="전체 기업 목록 · SIANALY"><meta property="og:url" content="https://sianaly.com/companies"><meta property="og:image" content="https://sianaly.com/og-image.png?v=2">
<link rel="canonical" href="https://sianaly.com/companies"><link rel="stylesheet" href="/legal.css?v=20261108"><link rel="stylesheet" href="/site-contact.css?v=20261108-member-legal">
<!-- Generated by scripts/build-company-directory.cjs. Do not edit by hand. -->
<style>
.dir-summary{color:#5b6779;font-size:14px;line-height:1.7}
.dir-market{margin-top:34px}.dir-market>h2{display:flex;align-items:baseline;gap:8px}.dir-market>h2 span{font-size:13px;font-weight:400;color:#8b95a5}
.dir-nav{display:flex;flex-wrap:wrap;gap:6px;margin:12px 0 6px}.dir-nav a{padding:6px 10px;border:1px solid #dfe5ed;border-radius:999px;font-size:12px;color:#43597a;text-decoration:none}.dir-nav a span{color:#9aa3b0}
.dir-group h3{font-size:15px;margin:26px 0 8px;color:#173d73}.dir-group h3 span{font-size:12px;font-weight:400;color:#9aa3b0}
.dir-group ul{list-style:none;margin:0;padding:0;display:grid;grid-template-columns:repeat(auto-fill,minmax(150px,1fr));gap:2px 14px}
.dir-group li{display:flex;align-items:baseline;gap:6px;padding:5px 0;border-bottom:1px solid #f0f2f6;min-width:0}
.dir-group li a{color:#17243b;text-decoration:none;font-size:14px;overflow:hidden;text-overflow:ellipsis;white-space:nowrap}.dir-group li a:hover{color:#2563eb;text-decoration:underline}
.dir-group li small{flex:none;font-size:11px;color:#9aa3b0}
</style></head>
<body><header class="legal-header"><a href="/" aria-label="SIANALY 홈"><img src="/sianaly-symbol.svg" width="34" height="34" alt="SIANALY"></a><a href="/">홈으로</a></header>
<main class="legal-main"><p class="legal-eyebrow">SIANALY 기업 목록</p><h1>전체 기업 목록</h1>
<p class="dir-summary">코스피·코스닥 상장 기업 ${total.toLocaleString('ko-KR')}곳을 시장과 업종별로 모았습니다. 업종 안에서는 시가총액 기준 순서이며, 우선주는 보통주 페이지에서 함께 볼 수 있습니다.</p>
${sections.map(s=>`<section class="dir-market" id="${s.market.toLowerCase()}"><h2>${s.label} <span>${s.count.toLocaleString('ko-KR')}곳</span></h2><nav class="dir-nav" aria-label="${s.label} 업종">${s.nav}</nav>\n${s.body}</section>`).join('\n')}
</main>
<footer class="site-contact"><div class="footer-brand">SIANALY</div><p class="investment-notice">SIANALY의 기업 정보와 분석은 참고용 자료이며 특정 금융상품의 매수·매도나 수익을 보장하지 않습니다. 투자 판단과 그 결과에 대한 책임은 이용자 본인에게 있습니다. 자료에는 오류나 갱신 지연이 있을 수 있으므로 원문 공시와 최신 자료를 확인해 주세요.</p><div class="site-contact-links"><a href="/terms">이용약관</a><a href="/privacy" class="privacy-link">개인정보 처리방침</a><a href="/data-guide">자료 출처·투자 유의사항</a><span>문의 및 제안</span><a href="mailto:sianaly11@gmail.com">sianaly11@gmail.com</a></div></footer>
</body></html>
`;
}

if(require.main===module){
 const html=buildDirectory();
 if(process.argv.includes('--check')){
  const current=fs.existsSync(output)?fs.readFileSync(output,'utf8').replace(/\r\n/g,'\n'):'';
  if(current!==html){console.error('companies.html is out of date. Run: node scripts/build-company-directory.cjs');process.exitCode=1;}
  else console.log('companies.html is up to date.');
 }else{fs.writeFileSync(output,html);console.log('Wrote companies.html: '+(html.match(/<li>/g)||[]).length+' companies.');}
}
module.exports={buildDirectory};

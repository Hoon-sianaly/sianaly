const assert=require('node:assert/strict');
const {requiredTerms,hasExplanation}=require('./glossary-rules.cjs');
const record=text=>({profile:{},overview:{summary:text},financials:{}});
const names=text=>requiredTerms(record(text)).map(([name])=>name);
assert(names('전방산업의 수요를 봅니다.').includes('전방산업'));
assert(!names('전방산업의 수요를 봅니다.').includes('방산'));
assert(names('방산 수출').includes('방산'));
assert(names('IPTV 가입자').includes('IPTV'));
assert(!names('IPTV 가입자').includes('IP'));
assert(!names('스테인리스 강관을 공급합니다.').includes('리스'));
assert(!names('폴리스티렌 소재를 제조합니다.').includes('리스'));
assert(names('차량 할부·리스 서비스를 제공합니다.').includes('리스'));
assert(names('스테인리스 생산 설비의 리스료를 지급합니다.').includes('리스'));
assert(names('아티스트 IP 사업').includes('IP'));
assert(names('IFRS17 보험수익').includes('IFRS 17'));
assert(names('PF 보증 부담').includes('프로젝트 금융'));
assert(!names('PF 보증 부담').includes('PF'));
assert(!names('원료비 미수금').includes('미수금'));
assert(hasExplanation([{name:'보험계약서비스마진(CSM)',desc:'설명'}],'보험계약서비스마진'));
assert(!hasExplanation([],'파운드리'));
assert.deepEqual(requiredTerms(record('제품을 판매합니다.')),[]);
assert(requiredTerms(record('제품을 판매합니다.'),{basis:'consolidated'}).some(([name])=>name==='연결 기준'));
console.log('Passed: glossary relevance, acronym boundaries, aliases, shared basis and empty simple text.');
